def env_over(state: CuarentaState) -> CuarentaEnv:
    """
    A throwaway env whose `state` is `state`.

    A couple of helpers in the ISMCTS package are written as methods that expect an env
    (notably `Determinizer`, which reads `env.state`), so this wraps a bare state for
    them without mutating anything that matters.
    """
    env = CuarentaEnv(seed=0)
    env.state = state
    return env


def public_key(state: CuarentaState) -> tuple:
    """
    Hashable description of everything EVERY seat can see.

    ReBeL's unit of search is the public state, so this is the identity of an information
    set up to the acting player's private hand: two positions with the same key differ
    only in cards the acting player holds. Used to key the solver's strategy/regret
    tables.

    Public here means: the face-up table, both capture piles, the scores, whose turn it
    is, how many turns each seat has taken in this deal, how many cards are left in the
    deck, and the last card placed (it is on the table, so it is public). Hands are the
    only hidden state in Cuarenta.
    """
    return (
        state.current_player,
        tuple(sorted(c.index for c in state.table)),
        tuple(sorted(c.index for c in state.cards_captured[0])),
        tuple(sorted(c.index for c in state.cards_captured[1])),
        tuple(int(s) for s in state.scores),
        tuple(int(p) for p in state.plays_this_deal),
        len(state.deck),
        state.last_placed.index if state.last_placed is not None else -1,
    )
